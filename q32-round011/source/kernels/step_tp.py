def _dsw(dst, src, on):
    """with on=1: through GpSimd's software DGE (the write of the all-reduce input buffer, which waits on the layer's
    dependency chain), so the Sync engine's in-order weight queue does not wait behind it (round 003)"""
    if on == 2:   # static descriptors (generated by the runtime at load), round 004 experiment
        nisa.dma_copy(dst=dst, src=src, dge_mode=nisa.dge_mode.none)
    elif on >= 3:   # round 006 experiments: 3 hwdge on the Scalar queue, 4 / 5 static triggered by GpSimd / Scalar
        _dq(dst, src, on)
    elif on:
        nisa.dma_copy(dst=dst, src=src, dge_mode=nisa.dge_mode.swdge)
    else:
        nisa.dma_copy(dst=dst, src=src)


def _dq(dst, src, on):
    """round 006: DMA trigger variants for the all-reduce chain (hb write CCQ, read-back RBQ): 3 = hwdge on the
    Scalar engine's queue, 4 = static descriptors triggered by GpSimd, 5 = static triggered by Scalar,
    6 = hwdge on the Sync queue"""
    if on == 3:
        nisa.dma_copy(dst=dst, src=src, dge_mode=nisa.dge_mode.hwdge, engine=nisa.engine.scalar)
    elif on == 4:
        nisa.dma_copy(dst=dst, src=src, dge_mode=nisa.dge_mode.none, engine=nisa.engine.gpsimd)
    elif on == 5:
        nisa.dma_copy(dst=dst, src=src, dge_mode=nisa.dge_mode.none, engine=nisa.engine.scalar)
    else:
        nisa.dma_copy(dst=dst, src=src, dge_mode=nisa.dge_mode.hwdge, engine=nisa.engine.sync)


def _embed_g(embed, t_sb, HT):
    """embedding row of token t (register) -> column layout h [128, HT] fp32 (lab 1 step_g._embed_g)"""
    treg = nisa.register_alloc()
    nisa.register_load(treg, t_sb)
    eb = nl.ndarray((128, HT), dtype=nl.bfloat16, buffer=nl.sbuf)
    nisa.dma_copy(dst=eb, src=embed.ap(pattern=[[1, 128], [128, HT]], offset=0, scalar_offset=treg, indirect_dim=0))
    h = nl.ndarray((128, HT), dtype=nl.float32, buffer=nl.sbuf)
    nisa.tensor_copy(dst=h, src=eb)
    return h


def _xchg_add_tp(part, pid, rg, W):
    """part [128, n] fp32 on each physical core of each rank -> sum over all 2W cores (on every core)."""
    n = part.shape[1]
    mine = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    nisa.tensor_copy(dst=mine, src=part)
    red = mine
    if W > 1:
        red = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
        ncc.all_reduce(srcs=[mine], dsts=[red], op=nl.add, replica_group=rg)
    other = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    nisa.sendrecv(src=red, dst=other, send_to_rank=1 - pid, recv_from_rank=1 - pid, pipe_id=0,
                  dma_engine=nisa.dma_engine.gpsimd_dma)
    s = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    nisa.tensor_tensor(dst=s, data1=red, data2=other, op=nl.add)
    return s


def _prefetch(W, KT, SL, n_slabs, hw, qi):
    """issue the DMAs of the first n_slabs weight slabs (SL n-tiles each) of W [128, NT*KT*128] into SBUF now"""
    tiles = []
    for i in range(n_slabs):
        wt = nl.ndarray((128, SL * KT * 128), dtype=W.dtype, buffer=nl.sbuf)
        _dma(wt, W[:, i * SL * KT * 128:(i + 1) * SL * KT * 128], qi, hw)
        qi += 1
        tiles.append(wt)
    return tiles, qi


def _prefetch_into(W, KT, SL, bufs, hw, qi):
    """_prefetch into caller-owned tiles (PQP: allocated once per step, so the next layer's QKV slabs do not share
    SBUF with this layer's in-flight slabs and can be issued as early as the scheduler likes)"""
    for i in range(len(bufs)):
        _dma(bufs[i], W[:, i * SL * KT * 128:(i + 1) * SL * KT * 128], qi, hw)
        qi += 1
    return bufs, qi


def _gemv_pf(xT, W, KT, NT, ps, SL, hw, qi, pre, out=None):
    """ps[:, nt] = W_tile(nt, :)^T @ xT for nt in [0, NT); the first len(pre) slabs come from pre-loaded tiles"""
    for i in range(len(pre)):
        for t in range(SL):
            nt = i * SL + t
            for k in range(KT):
                nisa.nc_matmul(dst=ps[:, nt:nt + 1], stationary=pre[i][:, (t * KT + k) * 128:(t * KT + k + 1) * 128],
                               moving=xT[:, k:k + 1])
        if out is not None:
            nisa.tensor_copy(dst=out[:, i * SL:(i + 1) * SL], src=ps[:, i * SL:(i + 1) * SL])
    return _gemv(xT, W, KT, len(pre) * SL, NT, ps, len(pre) * SL, SL, hw, qi, out)


def _ring_plan(plan, W, KT, nt0, nt1, spt):
    """RING (round 006): append the weight slabs of a GEMV (spt output tiles each, the last one shorter) to the
    step's slab plan, in the order _gemv_ring consumes them"""
    nt = nt0
    while nt < nt1:
        nb = spt
        if nt1 - nt < spt:
            nb = nt1 - nt
        plan.append((W, nt * KT * 128, nb * KT * 128))
        nt += nb


def _ring_load(ring, j, hw):
    bufs = ring[0]
    e = ring[1][j]
    W = e[0]
    _dma(bufs[j % len(bufs)][:, 0:e[2]], W[:, e[1]:e[1] + e[2]], 0, hw)


def _ring_take(ring, hw):
    """the next slab of the plan (its SBUF view); first issues the load of the slab N - 1 ahead into the buffer
    that the previous slab used (its matmuls are already emitted: the DMA waits only for them)"""
    bufs = ring[0]
    st = ring[2]
    s = st[0]
    j = s + len(bufs) - 1
    if j < len(ring[1]):
        _ring_load(ring, j, hw)
    st[0] = s + 1
    return bufs[s % len(bufs)][:, 0:ring[1][s][2]]


def _gemv_ring(xT, KT, nt0, nt1, ps, c0, ring, hw, spt, out=None, oc=0):
    """_gemv with the slabs taken from the ring (same matmuls in the same order as _gemv). With out (RCP): each
    slab's finished PSUM columns are copied to out[:, oc + (c - c0)] right after its matmuls, so TensorE signals
    the end of every slab (the ring DMA reusing the buffer can wait for exactly that)"""
    nt = nt0
    c = c0
    while nt < nt1:
        nb = spt
        if nt1 - nt < spt:
            nb = nt1 - nt
        wt = _ring_take(ring, hw)
        cs = c
        for t in range(nb):
            for k in range(KT):
                nisa.nc_matmul(dst=ps[:, c:c + 1], stationary=wt[:, (t * KT + k) * 128:(t * KT + k + 1) * 128],
                               moving=xT[:, k:k + 1])
            c += 1
        if out is not None:
            nisa.tensor_copy(dst=out[:, oc + cs - c0:oc + c - c0], src=ps[:, cs:c])
        nt += nb



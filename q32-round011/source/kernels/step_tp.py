def _qkv_slabs(Wq, KT, NQL, pid, SL, hw, qi):
    """KVS: the QKV slabs of virtual core pid: the NQL q tiles in slabs of SL tiles, then ONE kv tile, 4 + pid
    (core 0 projects k, core 1 projects v: the kv head is the rank's, so the two cores used to project both; round 004).
    Returns [(tile, first column of qkv_ps, n tiles)]."""
    out = []
    t0 = 0
    while t0 < NQL:
        nb = SL
        if NQL - t0 < SL:
            nb = NQL - t0
        wt = nl.ndarray((128, nb * KT * 128), dtype=Wq.dtype, buffer=nl.sbuf)
        _dma(wt, Wq[:, t0 * KT * 128:(t0 + nb) * KT * 128], qi, hw)
        qi += 1
        out.append((wt, t0, nb))
        t0 += nb
    wt = nl.ndarray((128, KT * 128), dtype=Wq.dtype, buffer=nl.sbuf)
    _dma(wt, Wq[:, (NQL + pid) * KT * 128:(NQL + pid + 1) * KT * 128], qi, hw)
    qi += 1
    out.append((wt, NQL, 1))
    return out, qi


def _qkv_mm(xT, KT, ps, slabs):
    for i in range(len(slabs)):
        wt = slabs[i][0]
        c0 = slabs[i][1]
        for t in range(slabs[i][2]):
            for k in range(KT):
                nisa.nc_matmul(dst=ps[:, c0 + t:c0 + t + 1], stationary=wt[:, (t * KT + k) * 128:(t * KT + k + 1) * 128],
                               moving=xT[:, k:k + 1])


IPC, ITF, IH = 1600, 12, 64   # HALF: intermediate rows per virtual core = ITF full tiles + one IH-row half tile


def _gu_half_slabs(KT, SL):
    """HALF wgu layout (src/engine.cpp layout_gu_half): [(element offset, full tiles, half, first psum column)]"""
    out = []
    for m in range(2):
        base = m * (ITF * KT * 128 + KT * IH)
        t = 0
        while t < ITF:
            nb = SL
            if ITF - t < SL:
                nb = ITF - t
            out.append((base + t * KT * 128, nb, 0, m * (ITF + 1) + t))
            t += nb
        out.append((base + ITF * KT * 128, 0, 1, m * (ITF + 1) + ITF))
    return out


def _gu_half_load(W, KT, sl, hw, qi):
    n = sl[1] * KT * 128
    if sl[2]:
        n = KT * IH
    wt = nl.ndarray((128, n), dtype=W.dtype, buffer=nl.sbuf)
    _dma(wt, W[:, sl[0]:sl[0] + n], qi, hw)
    return wt, qi + 1


def _gu_half_mm(xT, KT, ps, sl, wt):
    if sl[2]:
        for k in range(KT):
            nisa.nc_matmul(dst=ps[0:IH, sl[3]:sl[3] + 1], stationary=wt[:, k * IH:(k + 1) * IH], moving=xT[:, k:k + 1])
    else:
        for t in range(sl[1]):
            c = sl[3] + t
            for k in range(KT):
                nisa.nc_matmul(dst=ps[:, c:c + 1], stationary=wt[:, (t * KT + k) * 128:(t * KT + k + 1) * 128],
                               moving=xT[:, k:k + 1])


def _down_half(act, Wd, HT, ps, SL, hw, qi):
    """HALF wd layout: region A [128, (nt, ITF k-tiles, 128)], region B [IH partitions, (nt, 128)]"""
    wb = nl.ndarray((IH, HT * 128), dtype=Wd.dtype, buffer=nl.sbuf)
    _dma(wb, Wd[0:IH, HT * ITF * 128:HT * ITF * 128 + HT * 128], qi, hw)
    qi += 1
    nt = 0
    while nt < HT:
        nb = SL
        if HT - nt < SL:
            nb = HT - nt
        wa = nl.ndarray((128, nb * ITF * 128), dtype=Wd.dtype, buffer=nl.sbuf)
        _dma(wa, Wd[:, nt * ITF * 128:(nt + nb) * ITF * 128], qi, hw)
        qi += 1
        for t in range(nb):
            c = nt + t
            for k in range(ITF):
                nisa.nc_matmul(dst=ps[:, c:c + 1], stationary=wa[:, (t * ITF + k) * 128:(t * ITF + k + 1) * 128],
                               moving=act[:, k:k + 1])
            nisa.nc_matmul(dst=ps[:, c:c + 1], stationary=wb[:, c * 128:(c + 1) * 128], moving=act[0:IH, ITF:ITF + 1])
        nt += nb
    return qi


def _mpd_slabs(SL):
    """MPD (round 011) gate/up slabs of the MP layout (wgp: 12 gate + 12 up tiles + one packed tile whose output
    columns 0-63 are the gate half and 64-127 the up half of this core's last 64 rows): [(first tile, n tiles)]"""
    out = []
    t = 0
    while t < 2 * ITF:
        nb = SL
        if 2 * ITF - t < SL:
            nb = 2 * ITF - t
        out.append((t, nb))
        t += nb
    if MPL_[0] == 2:   # timing only: no packed tile (24 tiles in 2-tile slabs)
        return out
    if MPL_[0] == 3:   # the packed tile first (one 1-tile slab), then the 12 2-tile slabs
        return [(2 * ITF, 1)] + out
    if MPL_[0]:   # the packed tile in the last slab (3 tiles)
        out[-1] = (out[-1][0], out[-1][1] + 1)
    else:
        out.append((2 * ITF, 1))
    return out


def _mpd_load(W, KT, sl, hw, qi):
    wt = nl.ndarray((128, sl[1] * KT * 128), dtype=W.dtype, buffer=nl.sbuf)
    _dma(wt, W[:, sl[0] * KT * 128:(sl[0] + sl[1]) * KT * 128], qi, hw)
    return wt, qi + 1


def _mpd_mm(xT, KT, ps, sl, wt):
    for t in range(sl[1]):
        c = sl[0] + t
        for k in range(KT):
            nisa.nc_matmul(dst=ps[:, c:c + 1], stationary=wt[:, (t * KT + k) * 128:(t * KT + k + 1) * 128],
                           moving=xT[:, k:k + 1])


def _gemv3(xT, Wm, KT, NT, ps, SL, KS):
    """round 011 (DN3): ps[:, nt] = sum_{k < KS} W_tile(nt, k)^T @ xT[:, k], W [128, NT*KT*128] in HBM; each slab of SL
    output tiles is one DMA into a 3-D tile [128, SL, KS * 128] through an access pattern (KS < KT: a prefix of the
    k-tiles of every output tile)"""
    nt = 0
    while nt < NT:
        nb = SL
        if NT - nt < SL:
            nb = NT - nt
        wt = nl.ndarray((128, nb, KS * 128), dtype=Wm.dtype, buffer=nl.sbuf)
        nisa.dma_copy(dst=wt, src=Wm.ap(pattern=[[NT * KT * 128, 128], [KT * 128, nb], [1, KS * 128]], offset=nt * KT * 128),
                      dge_mode=nisa.dge_mode.hwdge, engine=nisa.engine.sync)
        for t in range(nb):
            for k in range(KS):
                nisa.nc_matmul(dst=ps[:, nt + t:nt + t + 1], stationary=wt[:, t, k * 128:(k + 1) * 128], moving=xT[:, k:k + 1])
        nt += nb


def _xchg_add_sbar(part, pid, rg, W):
    """HBMCC=2 (round 004 experiment): two-core sum by sendrecv (as the HBM variant), then an SBUF all_reduce of the
    sum by each physical core (both hold the same values): no HBM write / read-back DMA on the chain"""
    n = part.shape[1]
    mine = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    nisa.tensor_copy(dst=mine, src=part)
    other = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    nisa.sendrecv(src=mine, dst=other, send_to_rank=1 - pid, recv_from_rank=1 - pid, pipe_id=0,
                  dma_engine=nisa.dma_engine.gpsimd_dma)
    s2 = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    nisa.tensor_tensor(dst=s2, data1=mine, data2=other, op=nl.add)
    red = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    ncc.all_reduce(srcs=[s2], dsts=[red], op=nl.add, replica_group=rg)
    return red


def _xchg_add_tp_hbm(part, pid, rg, W, hb, hr, CCQ=0, RBQ=0, copied=False):
    """HBM variant: sum the two physical cores first (sendrecv), write the logical core's partial to an internal
    HBM buffer hb (both cores write the same bytes), all_reduce hb -> hr in HBM over the ranks (an HBM collective
    runs once per logical core), read hr back on both cores."""
    n = part.shape[1]
    if copied:   # part is already the SBUF fp32 copy (RCP)
        mine = part
    else:
        mine = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
        nisa.tensor_copy(dst=mine, src=part)
    other = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    nisa.sendrecv(src=mine, dst=other, send_to_rank=1 - pid, recv_from_rank=1 - pid, pipe_id=0,
                  dma_engine=nisa.dma_engine.gpsimd_dma)
    s2 = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    nisa.tensor_tensor(dst=s2, data1=mine, data2=other, op=nl.add)
    _dsw(hb, s2, CCQ)
    ncc.all_reduce(srcs=[hb], dsts=[hr], op=nl.add, replica_group=rg)
    s = nl.ndarray((128, n), dtype=nl.float32, buffer=nl.sbuf)
    if RBQ == 2:
        nisa.dma_copy(dst=s, src=hr, dge_mode=nisa.dge_mode.none)
    elif RBQ >= 3:
        _dq(s, hr, RBQ)
    else:
        nisa.dma_copy(dst=s, src=hr)   # read back on the default queue (on software DGE: 920 vs 894 ms per 64 tokens)
    return s


def _layer_tp(h, l, pid, ln1, ln2, qn, kn, wqkv, wo, wgu, wd, rot_sb, kcache, vcache,
              preg, pb, cs_col, sn_col, ones, ident, idf, ones16, TB, SL, hw, HT, NQL, NKL, ITL, rg, W, PF=0, pre_qkv=None, hbuf=None,
              vreg=None, VCH=1, PFG=-1, CCQ=0, KVS=0, qbuf=None, HALF=0, RBQ=0, KVQ=0, PFO=0, SLO=0, CCQM=-1, RBQM=-1, ring=None, BCP=0, MPD=0, wgp=None, wdh=None, wgx=None):
    HID = HT * 128
    G = NQL // NKL
    mpdc = False
    pre_o = None
    if isinstance(pre_qkv, tuple):   # PFO: (next-layer QKV slabs, next-layer o_proj slabs) from the previous layer
        pre_o = pre_qkv[1]
        pre_qkv = pre_qkv[0]
    TMAX = vcache.shape[2]
    NT = TB // 128
    NS = NT + 1
    qi = 0
    kall = nl.ndarray((D, NKL, TB), dtype=nl.bfloat16, buffer=nl.sbuf)
    vall = nl.ndarray((128, NT, NKL * D), dtype=nl.bfloat16, buffer=nl.sbuf)
    for hh in range(NKL):
        if KVQ == 2:   # static descriptors: off the weight queue (round 004)
            nisa.dma_copy(dst=kall[:, hh, :], src=kcache[l, pid, hh, :, 0:TB], dge_mode=nisa.dge_mode.none)
        else:
            _dma(kall[:, hh, :], kcache[l, pid, hh, :, 0:TB], qi, hw)
        qi += 1
    if VPERM:   # one DMA, NT x 256 B contiguous per partition (row p * VJ + j holds token 128 j + p)
        VJ = TMAX // 128
        c0 = 0
        while c0 < NT:
            n = VCH
            if NT - c0 < VCH:
                n = NT - c0
            vsrc = vcache[l, pid].ap(pattern=[[VJ * NKL * D, 128], [NKL * D, n], [1, NKL * D]], offset=c0 * NKL * D)
            if KVQ == 2:
                nisa.dma_copy(dst=vall[:, c0:c0 + n, :], src=vsrc, dge_mode=nisa.dge_mode.none)
            else:
                _dma(vall[:, c0:c0 + n, :], vsrc, qi, hw)
            qi += 1
            c0 += n
    else:
        for j in range(NT):
            _dma(vall[:, j, :], vcache[l, pid, j * 128:(j + 1) * 128, :], qi, hw)
            qi += 1
    w1 = nl.ndarray((128, HT), dtype=nl.float32, buffer=nl.sbuf)
    nisa.dma_copy(dst=w1, src=ln1[l])
    w2 = nl.ndarray((128, HT), dtype=nl.float32, buffer=nl.sbuf)
    nisa.dma_copy(dst=w2, src=ln2[l])
    qnc = nl.ndarray((128, 1), dtype=nl.float32, buffer=nl.sbuf)
    nisa.dma_copy(dst=qnc, src=qn[l])
    knc = nl.ndarray((128, 1), dtype=nl.float32, buffer=nl.sbuf)
    nisa.dma_copy(dst=knc, src=kn[l])

    x1 = _rms_col(h, w1, HT, HID, ones, nl.bfloat16)
    NQKV = NQL + 2 * NKL
    qkv = nl.ndarray((128, NQKV), dtype=nl.float32, buffer=nl.sbuf)
    if KVS:   # core pid projects only kv tile NQL + pid (k on core 0, v on core 1); the other comes by sendrecv
        qkv_ps = nl.ndarray((128, NQL + 1), dtype=nl.float32, buffer=nl.psum)
        slabs = pre_qkv
        if slabs is None:
            slabs, qi = _qkv_slabs(wqkv[l, pid], HT, NQL, pid, SL, hw, qi)
        _qkv_mm(x1, HT, qkv_ps, slabs)
        assert NKL == 1
        own = nl.ndarray((128, 1), dtype=nl.float32, buffer=nl.sbuf)
        nisa.tensor_copy(dst=own, src=qkv_ps[:, NQL:NQL + 1])
        okv = nl.ndarray((128, 1), dtype=nl.float32, buffer=nl.sbuf)
        nisa.sendrecv(src=own, dst=okv, send_to_rank=1 - pid, recv_from_rank=1 - pid,
                      pipe_id=0, dma_engine=nisa.dma_engine.gpsimd_dma)

"""Generate the Engram hashing constants of DeepSeek-V4.1-Flash (run once by hand; outputs are committed).

Uses the official inference/engram.py (NgramHashState) with the checkpoint's tokenizer:
  data/engram_map.bin   int32[vocab] compressed token id per token id
  data/engram_consts.h  pad id, multipliers [2][4], primes [2][3][8], offsets [2][24]
Usage: python gen_engram.py MODEL_DIR
"""
import json, sys, os
import numpy as np
model_dir = sys.argv[1]
sys.path.insert(0, os.path.join(model_dir, 'inference'))
sys.path.insert(0, '/mnt/nvme1/ds-ref')
import deepseek_cpu as R
sys.modules['kernel'] = R.make_kernel_module()
from engram import EngramLayout, NgramHashState, build_compressed_token_map, compute_hash_multipliers
import model as M
from transformers import AutoTokenizer
cfg = json.load(open(os.path.join(model_dir, 'inference', 'config.json')))
args = M.ModelArgs(**cfg)
args.max_seq_len = 16
args.max_batch_size = 1
tok = AutoTokenizer.from_pretrained(model_dir)
layout = EngramLayout.from_args(args)
st = NgramHashState(args, layout, tok)
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', 'data')
tm = st.token_map.numpy().astype(np.int32)
tm.tofile(os.path.join(out, 'engram_map.bin'))
mult = st.multipliers.numpy(); primes = st.primes.numpy(); offs = st.offsets.numpy()
with open(os.path.join(out, 'engram_consts.h'), 'w') as f:
    f.write('// generated by tools/gen_engram.py from the official inference/engram.py\n#pragma once\n#include <cstdint>\n')
    f.write(f'static const int64_t ENGRAM_PAD = {int(st.pad_id)};\n')
    f.write(f'static const int ENGRAM_VOCAB = {tm.size};\n')
    f.write('static const int64_t ENGRAM_MULT[2][4] = {' + ','.join('{' + ','.join(str(int(v)) for v in r) + '}' for r in mult) + '};\n')
    f.write('static const int64_t ENGRAM_PRIME[2][3][8] = {' + ','.join('{' + ','.join('{' + ','.join(str(int(v)) for v in rr) + '}' for rr in r) + '}' for r in primes) + '};\n')
    f.write('static const int64_t ENGRAM_OFF[2][24] = {' + ','.join('{' + ','.join(str(int(v)) for v in r) + '}' for r in offs) + '};\n')
# self-check against the official hash on a random sequence
import torch
ids = torch.randint(0, 129280, (1, 7))
h = st(ids, 0)
np.save(os.path.join(here, 'engram_check.npy'), np.concatenate([ids.numpy().reshape(-1), h.numpy().reshape(-1)]))
print('ok', tm.size, mult, primes.shape, offs.shape, h.shape)

"""Generates k_layer_variants.py (one @nki.jit wrapper per fused-layer variant, explicit signatures so that NKI can
parse them) and the matching argument specs (layer_specs()).  Run by specs.py at import (pure Python)."""
import os

COMMON = ['h', 'premix', 'posv', 'fnT', 'hsc', 'hbs', 'anw', 'wqa', 'qnw', 'wqb', 'wkv', 'kvw', 'rotP', 'ropec', 'roper',
          'win', 'sink', 'woa', 'wob', 'fnTf', 'hscf', 'hbsf', 'fnw', 'wgT', 'gbias', 'wrank', 'lvalid']
ALL = COMMON[:-2] + ['ckv', 'cmask', 'cwkv', 'cwg', 'state', 'cnw', 'wk', 'knw', 'roperc', 'iwqb', 'iwp', 'kc', 'lstrict']


B2 = (512, 1024, 2048, 2560, 4096)                 # compressed buckets, ratio 2 (cache 4096 rows)
B1 = (512, 1024, 1536, 2048, 4096, 4608, 8192)     # ratio 1 (cache 8192 rows)


def variants_m():
    """4-token prefill variants: name -> (ratio, T, comp, index); comp 'pairs' = ratio-2 kv source"""
    v = {'layer4_w': (0, 0, None, False)}
    for T in B2:
        v[f'layer4_c2_{T}'] = (2, T, None, False)
        v[f'layer4_s2_{T}'] = (2, T, 'pairs', T >= 1024)
    for T in B1:
        v[f'layer4_c1_{T}'] = (1, T, None, False)
        v[f'layer4_s1_{T}'] = (1, T, 'emit', T >= 1024)
        if T >= 1024:
            v[f'layer4_i1_{T}'] = (1, T, None, True)
    return v


def variants_m8():
    """lab: 8-token prefill variants"""
    return {k.replace('layer4_', 'layer8_'): v for k, v in variants_m().items()}


def variants():
    """name -> (ratio, T, comp, index)"""
    v = {'layer_w': (0, 0, None, False)}
    for T in B2:
        v[f'layer_c2_{T}'] = (2, T, None, False)
        v[f'layer_s2store_{T}'] = (2, T, 'store', T >= 1024)
        v[f'layer_s2emit_{T}'] = (2, T, 'emit', T >= 1024)
    for T in B1:
        v[f'layer_c1_{T}'] = (1, T, None, False)
        v[f'layer_s1_{T}'] = (1, T, 'emit', T >= 1024)
        if T >= 1024:
            v[f'layer_i1_{T}'] = (1, T, None, True)
    return v


PACKED = ['y6', 's2', 'h2p', 'fmixp']


def variants_p():
    """decode variants whose input is the previous layer's packed MoE outputs (combine fused in front)"""
    return {k + '_p': v for k, v in variants().items() if k != 'layer_w'}


def args_of(ratio, T, comp, index, packed=False):
    a = list(COMMON)
    if packed:
        a = PACKED + a[1:]
    if ratio:
        a.append('ckv')
        if not index:
            a.append('cmask')
    if comp:
        a.append('cwkv')
        if ratio == 2:
            a += ['cwg'] + (['state'] if comp != 'pairs' else [])
        if comp in ('emit', 'pairs'):
            a += ['cnw', 'wk', 'knw', 'roperc']
    if index:
        a += ['iwqb', 'iwp', 'kc', 'lstrict']
    return a


SHARED = ['ws1', 'ws3', 'ws2']


def args_m(ratio, T, comp, index):
    """4-token variants: the shared expert of the group runs at the end of the attention half (helper core)"""
    return args_of(ratio, T, comp, index) + SHARED


def generate(path):
    lines = ['"""generated by gen_layer_variants.py: fused-layer variants"""', 'import nki', 'import k_layer as KL', '']
    for name, (ratio, T, comp, index) in variants().items():
        a = args_of(ratio, T, comp, index)
        call = ', '.join(x if x in a else 'None' for x in ALL)
        lines += ['@nki.jit', f'def {name}({", ".join(a)}):',
                  f'    return KL.layer_impl({call}, {ratio}, {T}, {comp!r}, {index}, wrank, lvalid)', '', '']
    for name, (ratio, T, comp, index) in variants_p().items():
        a = args_of(ratio, T, comp, index, True)
        call = ', '.join(x if x in a else 'None' for x in ALL)
        lines += ['@nki.jit', f'def {name}({", ".join(a)}):',
                  f'    return KL.layer_impl({call}, {ratio}, {T}, {comp!r}, {index}, wrank, lvalid, [y6, s2, h2p, fmixp])', '', '']
    for name, (ratio, T, comp, index) in variants_m().items():
        a = args_m(ratio, T, comp, index)
        call = ', '.join(x if x in a else 'None' for x in ALL)
        lines += ['@nki.jit', f'def {name}({", ".join(a)}):',
                  f'    return KL.layer_impl_m(4, {call}, {ratio}, {T}, {comp!r}, {index}, wrank, lvalid, [ws1, ws3, ws2])', '', '']
    for name, (ratio, T, comp, index) in variants_m8().items():
        a = args_of(ratio, T, comp, index)
        call = ', '.join(x if x in a else 'None' for x in ALL)
        lines += ['@nki.jit', f'def {name}({", ".join(a)}):',
                  f'    return KL.layer_impl_m(8, {call}, {ratio}, {T}, {comp!r}, {index}, wrank, lvalid)', '', '']
    src = '\n'.join(lines)
    if not os.path.exists(path) or open(path).read() != src:
        open(path, 'w').write(src)


if __name__ == '__main__':
    generate(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'k_layer_variants.py'))

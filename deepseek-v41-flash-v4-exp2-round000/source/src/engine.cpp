static Neff load_neff(const Blob& b, int vnc) {
  Neff n;
  CK(nrt_load(b.b, b.n, vnc, 1, &n.m));
  nrt_tensor_info_array_t* info = nullptr;
  CK(nrt_get_model_tensor_info(n.m, &info));
  for (uint64_t i = 0; i < info->tensor_count; i++) {
    auto& t = info->tensor_array[i];
    (t.usage == NRT_TENSOR_USAGE_INPUT ? n.in_size : n.out_size)[t.name] = t.size;
  }
  nrt_free_model_tensor_info(info);
  return n;
}


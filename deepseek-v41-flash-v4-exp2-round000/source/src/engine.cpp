static long spin_x = envl("DSV4_SPIN_X", 4000000), spin_stage = envl("DSV4_SPIN_STAGE", 2000000);
static long poll_mode = envl("DSV4_POLL", 1);   // 0: tight polling of execution completion, 1: back-off
// Idle pipeline-stage threads wait for their queue counter with umonitor / umwait (C0.1, wakes on the counter's
// cache-line write) instead of a pause loop: in decode ~40 of them wait at any time, and their pause loops slowed
// the threads that are in runtime calls (hyperthread siblings, power).  DSV4_SPIN_PAUSE=1: pause loops only (lab).
static bool use_umwait = getenv("DSV4_SPIN_PAUSE") == nullptr;
// which waits use umwait: the pipeline stage queues and the expert-phase pending waits.  Measured (p256 / p1024
// prefill of 4 successive requests, decode per 64 tokens): stage queues -9 % decode, prefill as with pause loops;
// pending waits -1.8 % decode more (with the self warm-up; before it the first prefill was ~8 % slower); the expert
// workers' queues (DSV4_UMW_X=1) no decode gain and prefill ~5 % slower (first request up to 25 %)
static bool umw_x = envl("DSV4_UMW_X", 0) != 0, umw_q = envl("DSV4_UMW_Q", 1) != 0, umw_p = envl("DSV4_UMW_P", 1) != 0;
static bool stage_sleep = getenv("DSV4_STAGE_SLEEP") != nullptr;
static uint64_t spin_first_tsc = (uint64_t)envl("DSV4_SPIN_FIRST_US", 0) * 2400;   // us (TSC 2.4 GHz)
// wait while a == 0 (until_nonzero) or while a > 0, for at most about `pauses` pause-loop iterations' worth of time
template <class A>
static inline void idle_wait(const A& a, bool until_nonzero, long pauses, bool umw) {
  auto busy = [&] { int v = a.load(std::memory_order_acquire); return until_nonzero ? v == 0 : v > 0; };
  if (!use_umwait || !umw) {
    for (long i = 0; i < pauses && busy(); i++) __builtin_ia32_pause();
    return;
  }
  const uint64_t t0 = __rdtsc(), end = t0 + (uint64_t)pauses * 100;
  // pause loop first: threads handed work every few ms (prefill stages) stay hot; long waits (decode) umwait
  const uint64_t spin_end = t0 + spin_first_tsc;
  while (busy() && __rdtsc() < spin_end) __builtin_ia32_pause();
  while (busy()) {
    _umonitor((void*)&a);
    if (!busy()) break;
    uint64_t t = __rdtsc();
    if (t > end) break;
    _umwait(1, t + 20000);   // C0.1; also returns after ~8 us (TSC deadline) or on an interrupt
  }
}
static std::mutex prof_mu;
static std::map<std::string, std::pair<double, long>> prof_acc;
static void prof_add(const std::string& k, double dt) {
  std::lock_guard<std::mutex> g(prof_mu);
  auto& a = prof_acc[k]; a.first += dt; a.second++;
}
static void prof_add2(const char* k, double dt) { prof_add(k, dt); }
static void prof_dump() {
  std::lock_guard<std::mutex> g(prof_mu);
  for (auto& kv : prof_acc) LOG("prof %-22s total %8.1f ms  n %6ld  avg %7.1f us", kv.first.c_str(), kv.second.first * 1e3, kv.second.second, kv.second.first / kv.second.second * 1e6);
  prof_acc.clear();
}

// the official MoE.forward adds each token's routed expert outputs in ascending expert id order (its loop runs over
// the experts): the host sorts every token's 6 (expert, weight) pairs that way before the experts run, so each
// kernel's rank-order sum is that order.  DSV4_RANK_ORDER=1 (lab): the router's order (rounds 001-006).
static bool rank_order = getenv("DSV4_RANK_ORDER") != nullptr;
static bool g_moeu_on = getenv("DSV4_NO_MOEU") == nullptr;   // lab: DSV4_NO_MOEU=1 runs moe4
static void sort6(int32_t* e, float* w) {
  if (rank_order) return;
  for (int a = 1; a < 6; a++)
    for (int b = a; b > 0 && e[b - 1] > e[b]; b--) { std::swap(e[b - 1], e[b]); std::swap(w[b - 1], w[b]); }
}

struct Call {  // one NEFF bound to its tensors
  Neff* neff = nullptr;
  nrt_tensor_set_t *in = nullptr, *out = nullptr;
  std::string what;
  void init(Neff* n, const std::string& w) {
    neff = n; what = w;
    CK(nrt_allocate_tensor_set(&in));
    CK(nrt_allocate_tensor_set(&out));
  }
  void bi(const char* name, const Dev& d) {
    auto it = neff->in_size.find(name);
    if (it == neff->in_size.end()) die(what + ": no input " + name);
    if (it->second != d.n) die(what + ": input " + name + " size " + std::to_string(d.n) + " != " + std::to_string(it->second));
    CK(nrt_add_tensor_to_tensor_set(in, name, d.t));
  }
  void bo(int i, const Dev& d) {
    std::string name = "output_" + std::to_string(i);
    auto it = neff->out_size.find(name);
    if (it == neff->out_size.end()) die(what + ": no " + name);
    if (it->second != d.n) die(what + ": " + name + " size " + std::to_string(d.n) + " != " + std::to_string(it->second));
    CK(nrt_add_tensor_to_tensor_set(out, name.c_str(), d.t));
  }
  void check() {
    // every input and output bound?
    for (auto& kv : neff->in_size) { nrt_tensor_t* t; if (nrt_get_tensor_from_tensor_set(in, kv.first.c_str(), &t) != NRT_SUCCESS) die(what + ": unbound input " + kv.first); }
    for (auto& kv : neff->out_size) { nrt_tensor_t* t; if (nrt_get_tensor_from_tensor_set(out, kv.first.c_str(), &t) != NRT_SUCCESS) die(what + ": unbound output " + kv.first); }
  }
  // queued execution (nrta_execute_schedule + polling costs ~150 us less than nrt_execute); the per-core queue
  // runs executions in order
  NRT_STATUS ret = NRT_SUCCESS;
  nrta_seq_t seq = 0;
  double t_launch = 0;
  bool inflight = false;
  void reap() { if (inflight) wait(); }   // collect a queued execution whose successor already completed
  void launch() {
    inflight = true;
    if (prof_on) t_launch = now_s();
    NRT_STATUS s;
    while ((s = nrta_execute_schedule(neff->m, in, out, 0, &ret, &seq)) == NRT_QUEUE_FULL) {}
    CK(s);
    if (prof_on) prof_add2(sched_tag, now_s() - t_launch);
  }
  void wait() {
    // poll with back-off: dozens of pipeline threads polling back to back starve the runtime's other calls
    bool done = false;
    for (int k = 0;; k++) {
      CK(nrta_is_completed(seq, &done));
      if (done) break;
      int spins = poll_mode == 0 ? 8 : (k < 64 ? 32 : 256);
      for (int i = 0; i < spins; i++) __builtin_ia32_pause();
    }
    inflight = false;
    if (ret != NRT_SUCCESS) die(what + ": execution failed: " + nrt_get_status_as_str(ret));
    if (prof_on) prof_add(what, now_s() - t_launch);
  }
  void run() { launch(); wait(); }
};

// ------------------------------------------------------------------------------------------------ RoPE tables
// precompute_freqs_cis(64, MAXPOS, orig, base, 16, 32, 1) of model.py, in fp32 like torch.
static void rope_tables(bool compress, std::vector<float>& cosT, std::vector<float>& sinT, std::vector<float>& csT) {
  const int dim = 64;
  double base = compress ? 160000.0 : 10000.0;
  int orig = compress ? 65536 : 0;
  float freqs[32];
  for (int i = 0; i < 32; i++) {
    float ex = (float)(2 * i) / (float)dim;
    freqs[i] = 1.0f / powf((float)base, ex);
  }
  if (orig > 0) {
    auto corrected = [&](double rot) { return dim * log(orig / (rot * 2 * M_PI)) / (2 * log(base)); };
    double low = std::max(floor(corrected(32)), 0.0), high = std::min(ceil(corrected(1)), (double)dim - 1);
    float den = (float)std::max(high - low, 1e-3);
    for (int i = 0; i < 32; i++) {
      float ramp = ((float)i - (float)low) / den;
      ramp = std::min(1.0f, std::max(0.0f, ramp));
      float smooth = 1.0f - ramp;
      freqs[i] = freqs[i] / 16.0f * (1.0f - smooth) + freqs[i] * smooth;
    }
  }
  cosT.assign((size_t)MAXPOS * 128, 1.0f);
  sinT.assign((size_t)MAXPOS * 128, 0.0f);
  csT.assign((size_t)MAXPOS * 64, 0.0f);
  for (int t = 0; t < MAXPOS; t++)
    for (int i = 0; i < 32; i++) {
      float a = (float)t * freqs[i];
      float c = cosf(a), s = sinf(a);
      cosT[(size_t)t * 128 + 64 + 2 * i] = c;
      cosT[(size_t)t * 128 + 65 + 2 * i] = c;
      sinT[(size_t)t * 128 + 64 + 2 * i] = -s;
      sinT[(size_t)t * 128 + 65 + 2 * i] = s;
      csT[(size_t)t * 64 + i] = c;
      csT[(size_t)t * 64 + 32 + i] = s;
    }
}

// ------------------------------------------------------------------------------------------------ the engine
// The tensors the 4-token prefill attention-half NEFFs (layer4_*) of a layer use.  Without attention helpers they
// are the home core's own (aliases); with them they live on a helper core: copies of the dense weights, its own
// window ring and compressed caches (the host writes the compressed rows to both copies), so that in prefill the
// home core runs only the 4-token MoE.  The window ring is copied to the home core before the first single-token

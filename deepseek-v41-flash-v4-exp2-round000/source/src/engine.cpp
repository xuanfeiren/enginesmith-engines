  // new compressed rows (index keys k, compressed kv c) of n consecutive cache rows from crow0: into this kv
  // source's caches now (its next tokens read them), into the caches of the layers sharing them by those cores'
  // worker threads (the job reaches them later; they wait for job->cw[layer] before running it)
  bool async_rows = getenv("DSV4_SYNC_ROWS") == nullptr;
  void share_rows(int l, Job* j, int crow0, int n, const uint8_t* k, const uint8_t* c) {
    dwrite(L[l].kc, k, (size_t)n * 256, (size_t)crow0 * 256);
    dwrite(L[l].ckv, c, (size_t)n * 1024, (size_t)crow0 * 1024);
    if (L[l].at.own) {   // the helper's copies (the next groups' attention there reads them)
      dwrite(L[l].at.kc, k, (size_t)n * 256, (size_t)crow0 * 256);
      dwrite(L[l].at.ckv, c, (size_t)n * 1024, (size_t)crow0 * 1024);
    }
    for (int m = l + 1; m < NL; m++) {
      if (kv_source_of(m) != l) continue;
      bool wk = is_index_source(m);
      if (spread_on && async_rows) {
        ExpJob* jb = new ExpJob();
        jb->own = true;
        jb->pending = &j->cw[m];
        std::vector<uint8_t> kv(k, k + (size_t)n * 256), cv(c, c + (size_t)n * 1024);
        jb->fn = [this, m, wk, crow0, n, kv = std::move(kv), cv = std::move(cv)] {
          dwrite(L[m].ckv, cv.data(), (size_t)n * 1024, (size_t)crow0 * 1024);
          if (wk) dwrite(L[m].kc, kv.data(), (size_t)n * 256, (size_t)crow0 * 256);
          if (L[m].at.own) {
            dwrite(L[m].at.ckv, cv.data(), (size_t)n * 1024, (size_t)crow0 * 1024);
            if (wk) dwrite(L[m].at.kc, kv.data(), (size_t)n * 256, (size_t)crow0 * 256);
          }
        };
        j->cw[m].fetch_add(1, std::memory_order_acq_rel);
        xq[L[m].vnc].push(jb);
      } else {
        dwrite(L[m].ckv, c, (size_t)n * 1024, (size_t)crow0 * 1024);
        if (wk) dwrite(L[m].kc, k, (size_t)n * 256, (size_t)crow0 * 256);
        if (L[m].at.own) {
          dwrite(L[m].at.ckv, c, (size_t)n * 1024, (size_t)crow0 * 1024);
          if (wk) dwrite(L[m].at.kc, k, (size_t)n * 256, (size_t)crow0 * 256);
        }
      }
    }
  }
  void wait_rows(int l, Job* j) {
    while (j->cw[l].load(std::memory_order_acquire) > 0) __builtin_ia32_pause();
  }

  // pipeline stages: the 40 layers, with the Engram of layers 1 and 14 as stages of their own (own cores)
  std::vector<int> stages;   // >= 0: layer; -1 - l: Engram before layer l
  void run_engram(int l, Job* j) {
    Layer& y = L[l];
    const size_t hb = (size_t)HC * D * 2;
    if (j->spread && j->packed) {   // decode: kv was launched when the step started (by run_tokens)
      while (j->ekv.load(std::memory_order_acquire) < (l == 1 ? 1 : 2)) __builtin_ia32_pause();
      dwrite(y.pk_in, j->h.data(), PK_N);
      y.c_comb_in.launch();
      j->packed = false;
      j->h.resize(hb);
      y.c_egate.run();
      y.c_comb_in.reap();
      y.c_ekv.reap();
      dread(y.h_eng, j->h.data(), hb);
      if (dump_f) {
        std::vector<uint8_t> hi(hb); dread(y.h_ein, hi.data(), hb);
        dump_rec(4000 + l, j->pos, hi.data(), hb); dump_rec(5000 + l, j->pos, j->h.data(), hb);
      }
      return;
    }
    if (j->M == 4 && !j->packed && !getenv("DSV4_NO_ENGRAM4")) {   // the group's 4 tokens in one NEFF
      std::vector<uint8_t> pk((size_t)4 * (24 * 256 + 24 * 8));
      for (int m = 0; m < 4; m++)
        engram_fill(y, l == 1 ? 0 : 1, j->pos + m, &pk[(size_t)m * 24 * 256], &pk[(size_t)4 * 24 * 256 + m * 24 * 8]);
      dwrite(y.epack4, pk.data(), pk.size());
      dwrite(y.h_ein4, j->h.data(), 4 * hb);
      y.c_engram4.run();
      dread(y.h_eng4, j->h.data(), 4 * hb);
      return;
    }
    for (int m = 0; m < j->M; m++) {
      engram_rows(y, l == 1 ? 0 : 1, j->pos + m);
      if (j->packed) {
        dwrite(y.pk_in, j->h.data(), PK_N);
        y.c_comb_in.launch();
        j->packed = false;
        j->h.resize(hb);
      } else {
        dwrite(y.h_ein, j->h.data() + m * hb, hb);
      }
      y.c_engram.run();
      dread(y.h_eng, j->h.data() + m * hb, hb);
    }
  }

  // ---- a 4-token prefill group through one layer (same per-token arithmetic as run_layer)
  // phase A: step tensor (residuals, positions, masks) and the queued attention half
  void run_layer4_a(int l, Job* j, int b) {
    wait_rows(l, j);
    Layer& y = L[l];
    bool hs = home_site(l, j->pos);
    Att4& A = hs ? y.ath : y.at;
    ring_to(l, hs ? 1 : 0);
    int r = y.ratio, p0 = j->pos, ti = r ? 1 : 0;
    const size_t hb = (size_t)HC * D * 2;
    int tcl = r ? (p0 + 4) / r : 0, T = r ? bucket(tcl, r) : 0;
    bool kernel_sel = r && is_index_source(l) && T >= 1024;
    std::vector<uint8_t>& st = stepbuf4[l];
    if (st.size() < S4_MASK + (size_t)4 * MAXPOS * 4) st.assign(S4_MASK + (size_t)4 * MAXPOS * 4, 0);
    if (l == 0) {
      const TensorRef& e = ck.get("embed.weight");
      j->h.resize(4 * hb);
      for (int m = 0; m < 4; m++)
        for (int i = 0; i < HC; i++) memcpy(&j->h[m * hb + (size_t)i * D * 2], e.data + (size_t)j->toks[m] * D * 2, D * 2);
    }
    memcpy(&st[S4_H], j->h.data(), 4 * hb);
    for (int m = 0; m < 4; m++) {
      int pos = p0 + m;
      int32_t pv[8] = {pos, pos & 127, r ? pos + 1 - r : 0, r ? pos / r : 0, r ? (pos + 1) / r : 0, 0, 0, 0};
      memcpy(&st[S4_POSV + m * 32], pv, 32);
      memcpy(&st[S4_PREMIX + m * 16], j->pm4[m], 16);
      float* rc = (float*)&st[S4_ROPEC + m * 1024];
      for (int p = 0; p < 128; p++) { rc[2 * p] = tab_cos[ti][(size_t)pos * 128 + p]; rc[2 * p + 1] = tab_sin[ti][(size_t)pos * 128 + p]; }
      memcpy(&st[S4_ROPER + m * 256], &tab_cs[ti][(size_t)pos * 64], 256);
      if (is_kv_source(l) && pos + 1 - r >= 0) memcpy(&st[S4_ROPERC + m * 256], &tab_cs[1][(size_t)(pos + 1 - r) * 64], 256);
    }
    size_t stn = S4_MASK;
    if (r && !kernel_sel) {
      if (is_index_source(l)) {
        std::vector<Job::Sel> v(4);
        for (int m = 0; m < 4; m++) v[m].tc = (p0 + m + 1) / r;
        j->sel4[l] = v;
      }
      auto it = j->sel4.find(index_source_of(l));
      if (it == j->sel4.end()) die("missing indexer selection (group)");
      for (int m = 0; m < 4; m++)
        attn_list(p0 + m, j->pl, r, &it->second[m], T, (float*)&st[S4_WRANK + m * 512],
                  (float*)&st[S4_LVALID + (size_t)m * LLIST * 4], (float*)&st[S4_MASK + (size_t)m * T * 4]);
      stn = S4_MASK + (size_t)4 * T * 4;
    } else {
      int nlist = r ? LLIST : 128;
      for (int m = 0; m < 4; m++)
        attn_list(p0 + m, j->pl, r, nullptr, T, (float*)&st[S4_WRANK + m * 512],
                  (float*)&st[S4_LVALID + (size_t)m * nlist * 4], nullptr);
    }
    write_tag = "write step4";
    dwrite(A.step4, st.data(), stn);
    write_tag = "host write";
    std::string vn = variant4_for(l, p0 + 3);
    sched_tag = "sched layer4";
    A.c_layer4[b].at(vn).launch();
    trace(l, p0, 1);
    sched_tag = "sched call";
  }

  // phase B: wait for the attention half, shared caches / selections, then the queued MoE
  void run_layer4_b(int l, Job* j, int b) {
    Layer& y = L[l];
    int r = y.ratio, p0 = j->pos;
    int tcl = r ? (p0 + 4) / r : 0, T = r ? bucket(tcl, r) : 0;
    bool kernel_sel = r && is_index_source(l) && T >= 1024;
    Att4& A = site_of(l, p0);
    A.c_layer4[b].at(variant4_for(l, p0 + 3)).wait();
    trace(l, p0, 2);
    if (A.own) {   // everything of the helper's outputs but the selection in one read; tdata = the MoE stage's input
      j->tdata.resize(M4_N);
      dread(A.apack[b], j->tdata.data(), is_kv_source(l) ? M4_N : M4_CP);
    }
    double tbw = prof_on ? now_s() : 0;
    struct G4 { double t; bool on; ~G4() { if (on) prof_add("l4 wait->moe4 launched", now_s() - t); } } g4{tbw, prof_on};
    if (is_kv_source(l)) {
      std::vector<uint8_t> cp(4 * 1280), kk(4 * 256), cc(4 * 1024);
      if (A.own) memcpy(cp.data(), j->tdata.data() + M4_CP, cp.size());
      else dread(A.cpack4[b], cp.data(), cp.size());
      int n = 0, crow0 = -1;
      for (int m = 0; m < 4; m++) {   // the emitted rows are consecutive cache rows
        int pos = p0 + m;
        if (!(r == 1 || (pos + 1) % 2 == 0)) continue;
        if (crow0 < 0) crow0 = pos / r;
        memcpy(&kk[n * 256], &cp[m * 1280], 256);
        memcpy(&cc[n * 1024], &cp[m * 1280 + 256], 1024);
        n++;
      }
      share_rows(l, j, crow0, n, kk.data(), cc.data());
    }
    if (kernel_sel) {
      std::vector<float> sv((size_t)4 * T);
      dread(A.sel4_t.at(T), sv.data(), sv.size() * 4);
      int J = T / 128;
      std::vector<Job::Sel> v(4);
      for (int m = 0; m < 4; m++) {
        v[m].tc = (p0 + m + 1) / r;
        v[m].all = false;
        const float* s = &sv[(size_t)m * T];
        for (int t = 0; t < T; t++) if (s[(size_t)(t % 128) * J + t / 128] != 0.f) v[m].idx.push_back(t);
        size_t want = std::min(512, v[m].tc);
        if (v[m].idx.size() != want) die("group indexer selected " + std::to_string(v[m].idx.size()) + " positions");
      }
      j->sel4[l] = std::move(v);
    }
    int32_t ri[32];
    if (A.own) memcpy(ri, j->tdata.data() + M4_RIDX, 128);
    else dread(A.ridx4[b], ri, 128);
    for (int k = 0; k < 32; k++) if (k % 8 < 6 && (ri[k] < 0 || ri[k] >= 384)) die("router index out of range at layer " + std::to_string(l));
    float rw4v[32];
    if (A.own) memcpy(rw4v, j->tdata.data() + M4_RW, 128); else dread(A.rw4[b], rw4v, 128);
    if (!rank_order) {   // ascending expert order per token, the weights alike
      for (int m = 0; m < 4; m++) sort6(ri + m * 8, rw4v + m * 8);
      if (A.own) memcpy(j->tdata.data() + M4_RW, rw4v, 128); else dwrite(A.rw4[b], rw4v, 128);
    }
    int e24[24];
    for (int m = 0; m < 4; m++)
      for (int k = 0; k < 6; k++) e24[m * 6 + k] = ri[m * 8 + k];
    { static FILE* rf = getenv("DSV4_ROUTES") ? fopen(getenv("DSV4_ROUTES"), "w") : nullptr; static std::mutex rmu;
      if (rf) { std::lock_guard<std::mutex> g(rmu); fprintf(rf, "%d %d", l, j->pos); for (int a = 0; a < 24; a++) fprintf(rf, " %d", e24[a]); fprintf(rf, "\n"); fflush(rf); } }
    if (prof_on) { int u = 0; for (int a = 0; a < 24; a++) { bool d = false; for (int c = 0; c < a; c++) d |= e24[c] == e24[a]; u += !d; } prof_add("uniq24", u * 1e-6); }
    if (A.own) { memcpy(j->te24, e24, sizeof e24); return; }   // the MoE stage on the home core follows
    if (y.tvnc >= 0) {   // the MoE runs in the twin stage: hand over its inputs
      const size_t hb = HB;
      j->tdata.resize(4 * D * 2 + 4 * hb + 4 * 96 + 128);
      uint8_t* td = j->tdata.data();
      dread(A.xffn4[b], td, 4 * D * 2);
      dread(A.h2_4[b], td + 4 * D * 2, 4 * hb);
      dread(A.rw4[b], td + 4 * D * 2 + 4 * hb + 4 * 96, 128);
      memcpy(j->te24, e24, sizeof e24);
      return;
    }
    double tb4 = prof_on ? now_s() : 0;
    launch_moe4(y, e24, rw4v, b);
    if (prof_on) prof_add("bind4+launch", now_s() - tb4);
    trace(-2000 - l, j->pos, 11);
  }

